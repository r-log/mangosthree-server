//
//   void mangos_montmul_adx(uint64_t* z, const uint64_t* x, const uint64_t* y,
//                           const uint64_t* m, uint64_t n0inv, uint64_t k);
//     z = x * y * 2^(-64k) mod m, for x, y < m, m odd, k a positive multiple of 4.
//   void mangos_montmul16_adx(z, x, y, m, n0inv), mangos_montmul32_adx(...)
//     the same for k = 16 and k = 32, unrolled.
//   void mangos_montsqr16_adx(uint64_t* z, const uint64_t* x, const uint64_t* m,
//                             uint64_t n0inv), mangos_montsqr32_adx(...)
//     z = x * x * 2^(-64k) mod m, for x < m, m odd.
//   z may alias x or y. Every result is canonical (below m).
//
// CIOS as in the C++ tiers (src/shared/Crypto/Montgomery.cpp): for each limb of x,
// add x_i * y into the accumulator t, then add the multiple of m that clears t[0]
// and drop that limb; after k rounds t is below 2m and one masked subtraction
// makes it canonical. The products from mulx (which leaves the flags alone) feed
// two independent carry chains, adcx on CF for the accumulator and adox on OF for
// the carry between products, so the two additions of every step overlap. In the
// generic procedure nothing inside a chain may touch the flags: pointers and
// counters advance with lea and the loops close with jrcxz, unrolled four limbs
// deep. The unrolled procedures have no loop inside a chain at all.
//
// The squaring forms x * x in a 2k+1-limb accumulator -- the upper triangle by
// rows, doubled by one add-with-carry chain, the diagonal squares by another --
// and reduces it in place, k rows of q_i * m at offset i, each row's carry folded
// into the next row's top limb: 1.5 k^2 products instead of 2 k^2.
//
// Constant-time: the instruction sequence, the loop counts and every address
// depend on k alone; the final subtraction is selected by a mask. Every frame is
// erased before returning.
//
// Register use, all procedures (after the prologue):
//   rdi z   rsi x   r10 y   r11 m   r8 n0inv   rdx multiplier   rax:rbx product
//   r12 carry   r13 zero   r14 the squaring's row carry   rcx, r15 pointers/counters
//   generic: r9 k*8, rbp frame pointer, t[j] at [rsp + 8 + 8j] (a scratch limb at [rsp])
//   unrolled: a fixed frame, t[j] at [rsp + 8 + 8j], the scratch limb at [rsp]
//
// Both ABIs are in this one source under WINDOWS_ABI, each with its unwind
// metadata: CFI for the ELF build, the MASM FRAME directives for ml64 (the
// translator src/tests/tools/gas2masm.py copies the Windows branch through; GAS
// never sees it).
// ---------------------------------------------------------------------------

