/**
 * @brief Splits part of an item stack into another destination slot.
 *
 * @param recv_data The received opcode packet.
 */
void ItemHandlers::HandleSplitItem(WorldSession& session, WorldPacket& recv_data)
{
    // DEBUG_LOG("WORLD: CMSG_SPLIT_ITEM");
    uint8 srcbag, srcslot, dstbag, dstslot;
    uint32 count;

    recv_data >> srcbag >> srcslot >> dstbag >> dstslot >> count;
    // DEBUG_LOG("STORAGE: receive srcbag = %u, srcslot = %u, dstbag = %u, dstslot = %u, count = %u", srcbag, srcslot, dstbag, dstslot, count);

    uint16 src = ((srcbag << 8) | srcslot);
    uint16 dst = ((dstbag << 8) | dstslot);

    if (src == dst)
    {
        return;
    }

    if (count == 0)
    {
        return;                                             // check count - if zero it's fake packet
    }

    if (!session.GetPlayer()->GetInventoryMgr().IsValidPos(srcbag, srcslot, true))
    {
        session.GetPlayer()->SendEquipError(EQUIP_ERR_ITEM_NOT_FOUND, NULL, NULL);
        return;
    }

    if (!session.GetPlayer()->GetInventoryMgr().IsValidPos(dstbag, dstslot, false))       // can be autostore pos
    {
        session.GetPlayer()->SendEquipError(EQUIP_ERR_ITEM_DOESNT_GO_TO_SLOT, NULL, NULL);
        return;
    }

    session.GetPlayer()->SplitItem(src, dst, count);
}

/**
 * @brief Swaps two equipped inventory slots.
 *
 * @param recv_data The received opcode packet.
 */
void ItemHandlers::HandleSwapInvItem(WorldSession& session, WorldPacket& recv_data)
{
    // DEBUG_LOG("WORLD: CMSG_SWAP_INV_ITEM");
    uint8 srcslot, dstslot;

    recv_data >> dstslot >> srcslot;
    // DEBUG_LOG("STORAGE: receive srcslot = %u, dstslot = %u", srcslot, dstslot);

    // prevent attempt swap same item to current position generated by client at special cheating sequence
    if (srcslot == dstslot)
    {
        return;
    }

    if (!session.GetPlayer()->GetInventoryMgr().IsValidPos(INVENTORY_SLOT_BAG_0, srcslot, true))
    {
        session.GetPlayer()->SendEquipError(EQUIP_ERR_ITEM_NOT_FOUND, NULL, NULL);
        return;
    }

    if (!session.GetPlayer()->GetInventoryMgr().IsValidPos(INVENTORY_SLOT_BAG_0, dstslot, true))
    {
        session.GetPlayer()->SendEquipError(EQUIP_ERR_ITEM_DOESNT_GO_TO_SLOT, NULL, NULL);
        return;
    }

    uint16 src = ((INVENTORY_SLOT_BAG_0 << 8) | srcslot);
    uint16 dst = ((INVENTORY_SLOT_BAG_0 << 8) | dstslot);

    session.GetPlayer()->SwapItem(src, dst);
}

/**
 * @brief Equips an item into a specific equipment slot.
 *
 * @param recv_data The received opcode packet.
 */
void ItemHandlers::HandleAutoEquipItemSlot(WorldSession& session, WorldPacket& recv_data)
{
    ObjectGuid itemGuid;
    uint8 dstslot;
    recv_data >> itemGuid >> dstslot;

    // cheating attempt, client should never send opcode in that case
    if (!InventoryMgr::IsEquipmentPos(INVENTORY_SLOT_BAG_0, dstslot))
    {
        return;
    }

    Item* item = session.GetPlayer()->GetInventoryMgr().GetItemByGuid(itemGuid);
    uint16 dstpos = dstslot | (INVENTORY_SLOT_BAG_0 << 8);

    if (!item || item->GetPos() == dstpos)
    {
        return;
    }

    session.GetPlayer()->SwapItem(item->GetPos(), dstpos);
}

/**
 * @brief Swaps two arbitrary item positions.
 *
 * @param recv_data The received opcode packet.
 */
void ItemHandlers::HandleSwapItem(WorldSession& session, WorldPacket& recv_data)
{
    // DEBUG_LOG("WORLD: CMSG_SWAP_ITEM");
    uint8 dstbag, dstslot, srcbag, srcslot;

    recv_data >> dstbag >> dstslot >> srcbag >> srcslot ;
    // DEBUG_LOG("STORAGE: receive srcbag = %u, srcslot = %u, dstbag = %u, dstslot = %u", srcbag, srcslot, dstbag, dstslot);

    uint16 src = ((srcbag << 8) | srcslot);
    uint16 dst = ((dstbag << 8) | dstslot);

    // prevent attempt swap same item to current position generated by client at special cheating sequence
    if (src == dst)
    {
        return;
    }

    if (!session.GetPlayer()->GetInventoryMgr().IsValidPos(srcbag, srcslot, true))
    {
        session.GetPlayer()->SendEquipError(EQUIP_ERR_ITEM_NOT_FOUND, NULL, NULL);
        return;
    }

    if (!session.GetPlayer()->GetInventoryMgr().IsValidPos(dstbag, dstslot, true))
    {
        session.GetPlayer()->SendEquipError(EQUIP_ERR_ITEM_DOESNT_GO_TO_SLOT, NULL, NULL);
        return;
    }

    session.GetPlayer()->SwapItem(src, dst);
}

/**
 * @brief Auto-equips an item from inventory or bank.
 *
 * @param recv_data The received opcode packet.
 */
void ItemHandlers::HandleAutoEquipItem(WorldSession& session, WorldPacket& recv_data)
{
    // DEBUG_LOG("WORLD: CMSG_AUTOEQUIP_ITEM");
    uint8 srcbag, srcslot;

    recv_data >> srcbag >> srcslot;
    // DEBUG_LOG("STORAGE: receive srcbag = %u, srcslot = %u", srcbag, srcslot);

    Item* pSrcItem  = session.GetPlayer()->GetInventoryMgr().GetItemByPos(srcbag, srcslot);
    if (!pSrcItem)
    {
        return;                                             // only at cheat
    }

    uint16 dest;
    InventoryResult msg = session.GetPlayer()->CanEquipItem(NULL_SLOT, dest, pSrcItem, !pSrcItem->IsBag());
    if (msg != EQUIP_ERR_OK)
    {
        session.GetPlayer()->SendEquipError(msg, pSrcItem, NULL);
        return;
    }

    uint16 src = pSrcItem->GetPos();
    if (dest == src)                                        // prevent equip in same slot, only at cheat
    {
        return;
    }

    Item* pDstItem = session.GetPlayer()->GetInventoryMgr().GetItemByPos(dest);
    if (!pDstItem)                                          // empty slot, simple case
    {
        session.GetPlayer()->RemoveItem(srcbag, srcslot, true);
        session.GetPlayer()->EquipItem(dest, pSrcItem, true);
        session.GetPlayer()->AutoUnequipOffhandIfNeed();
    }
    else                                                    // have currently equipped item, not simple case
    {
        uint8 dstbag = pDstItem->GetBagSlot();
        uint8 dstslot = pDstItem->GetSlot();

        msg = session.GetPlayer()->CanUnequipItem(dest, !pSrcItem->IsBag());
        if (msg != EQUIP_ERR_OK)
        {
            session.GetPlayer()->SendEquipError(msg, pDstItem, NULL);
            return;
        }

        // check dest->src move possibility
        ItemPosCountVec sSrc;
        uint16 eSrc = 0;
        if (session.GetPlayer()->GetInventoryMgr().IsInventoryPos(src))
        {
            msg = session.GetPlayer()->CanStoreItem(srcbag, srcslot, sSrc, pDstItem, true);
            if (msg != EQUIP_ERR_OK)
            {
                msg = session.GetPlayer()->CanStoreItem(srcbag, NULL_SLOT, sSrc, pDstItem, true);
            }
            if (msg != EQUIP_ERR_OK)
            {
                msg = session.GetPlayer()->CanStoreItem(NULL_BAG, NULL_SLOT, sSrc, pDstItem, true);
            }
        }
        else if (session.GetPlayer()->GetInventoryMgr().IsBankPos(src))
        {
            msg = session.GetPlayer()->CanBankItem(srcbag, srcslot, sSrc, pDstItem, true);
            if (msg != EQUIP_ERR_OK)
            {
                msg = session.GetPlayer()->CanBankItem(srcbag, NULL_SLOT, sSrc, pDstItem, true);
            }
            if (msg != EQUIP_ERR_OK)
            {
                msg = session.GetPlayer()->CanBankItem(NULL_BAG, NULL_SLOT, sSrc, pDstItem, true);
            }
        }
        else if (session.GetPlayer()->GetInventoryMgr().IsEquipmentPos(src))
        {
            msg = session.GetPlayer()->CanEquipItem(srcslot, eSrc, pDstItem, true);
            if (msg == EQUIP_ERR_OK)
            {
                msg = session.GetPlayer()->CanUnequipItem(eSrc, true);
            }
        }

        if (msg != EQUIP_ERR_OK)
        {
            session.GetPlayer()->SendEquipError(msg, pDstItem, pSrcItem);
            return;
        }

        // now do moves, remove...
        session.GetPlayer()->RemoveItem(dstbag, dstslot, false);
        session.GetPlayer()->RemoveItem(srcbag, srcslot, false);

        // add to dest
        session.GetPlayer()->EquipItem(dest, pSrcItem, true);

        // add to src
        if (session.GetPlayer()->GetInventoryMgr().IsInventoryPos(src))
        {
            session.GetPlayer()->StoreItem(sSrc, pDstItem, true);
        }
        else if (session.GetPlayer()->GetInventoryMgr().IsBankPos(src))
        {
            session.GetPlayer()->BankItem(sSrc, pDstItem, true);
        }
        else if (session.GetPlayer()->GetInventoryMgr().IsEquipmentPos(src))
        {
            session.GetPlayer()->EquipItem(eSrc, pDstItem, true);
        }

        session.GetPlayer()->AutoUnequipOffhandIfNeed();
    }
}

/**
 * @brief Destroys all or part of an item stack.
 *
 * @param recv_data The received opcode packet.
 */
void ItemHandlers::HandleDestroyItem(WorldSession& session, WorldPacket& recv_data)
{
    // DEBUG_LOG("WORLD: CMSG_DESTROYITEM");
    uint8 bag, slot, count, data1, data2, data3;

    recv_data >> bag >> slot >> count >> data1 >> data2 >> data3;
    // DEBUG_LOG("STORAGE: receive bag = %u, slot = %u, count = %u", bag, slot, count);

    uint16 pos = (bag << 8) | slot;

    // prevent drop unequipable items (in combat, for example) and non-empty bags
    if (session.GetPlayer()->GetInventoryMgr().IsEquipmentPos(pos) || session.GetPlayer()->GetInventoryMgr().IsBagPos(pos))
    {
        InventoryResult msg = session.GetPlayer()->CanUnequipItem(pos, false);
        if (msg != EQUIP_ERR_OK)
        {
            session.GetPlayer()->SendEquipError(msg, session.GetPlayer()->GetInventoryMgr().GetItemByPos(pos), NULL);
            return;
        }
    }

    Item* pItem  = session.GetPlayer()->GetInventoryMgr().GetItemByPos(bag, slot);
    if (!pItem)
    {
        session.GetPlayer()->SendEquipError(EQUIP_ERR_ITEM_NOT_FOUND, NULL, NULL);
        return;
    }

    // checked at client side and not have server side appropriate error output
    if (pItem->GetProto()->Flags & ITEM_FLAG_INDESTRUCTIBLE)
    {
        session.GetPlayer()->SendEquipError(EQUIP_ERR_CANT_DROP_SOULBOUND, NULL, NULL);
        return;
    }

    if (count)
    {
        uint32 i_count = count;
        session.GetPlayer()->DestroyItemCount(pItem, i_count, true);
    }
    else
    {
        session.GetPlayer()->DestroyItem(bag, slot, true);
    }
}

/**
 * @brief Handles a request to read a readable item.
 *
 * @param recv_data The received opcode packet.
 */
void ItemHandlers::HandleReadItem(WorldSession& session, WorldPacket& recv_data)
{
    // DEBUG_LOG("WORLD: Received opcode CMSG_READ_ITEM");

    uint8 bag, slot;
    recv_data >> bag >> slot;

    // sLog.outDetail("STORAGE: Read bag = %u, slot = %u", bag, slot);
    Item* pItem = session.GetPlayer()->GetInventoryMgr().GetItemByPos(bag, slot);

    if (pItem && pItem->GetProto()->PageText)
    {
        WorldPacket data;

        InventoryResult msg = session.GetPlayer()->CanUseItem(pItem);
        if (msg == EQUIP_ERR_OK)
        {
            data.Initialize(SMSG_READ_ITEM_OK, 8);
            DETAIL_LOG("STORAGE: Item page sent");
        }
        else
        {
            data.Initialize(SMSG_READ_ITEM_FAILED, 8);
            DETAIL_LOG("STORAGE: Unable to read item");
            session.GetPlayer()->SendEquipError(msg, pItem, NULL);
        }
        data << pItem->GetObjectGuid();
        session.SendPacket(&data);
    }
    else
    {
        session.GetPlayer()->SendEquipError(EQUIP_ERR_ITEM_NOT_FOUND, NULL, NULL);
    }
}

void ItemHandlers::HandleItemRefundInfoRequest(WorldSession& session, WorldPacket& recv_data)
{
    DEBUG_LOG("WORLD: CMSG_GET_ITEM_PURCHASE_DATA");

    ObjectGuid itemGuid;
    recv_data >> itemGuid;

    Item* item = session.GetPlayer()->GetInventoryMgr().GetItemByGuid(itemGuid);

    if (!item)
    {
        DEBUG_LOG("Item refund: item not found!");
        return;
    }

    if (!(item->GetProto()->Flags & ITEM_FLAG_REFUNDABLE))
    {
        DEBUG_LOG("Item refund: item not refundable!");
        return;
    }

    ItemPrototype const* proto = item->GetProto();

    // Calculate remaining refund time (2 hours from purchase)
    uint32 createPlayedTime = item->GetUInt32Value(ITEM_FIELD_CREATE_PLAYED_TIME);
    uint32 curPlayedTime = session.GetPlayer()->GetTotalPlayedTime();
    uint32 maxRefundTime = 2 * HOUR;
    uint32 remainingTime = 0;
    if (curPlayedTime - createPlayedTime < maxRefundTime)
    {
        remainingTime = maxRefundTime - (curPlayedTime - createPlayedTime);
    }

    // Send SMSG_SET_ITEM_PURCHASE_DATA
    // 5 currency slots + 5 item slots in extended cost structure
    WorldPacket data(SMSG_SET_ITEM_PURCHASE_DATA, 8 + 4 + 4 * 5 * 2 + 4 * 5 * 2 + 4);
    data << itemGuid;
    data << uint32(remainingTime);

    // Currency/token costs (from extended cost, 5 slots)
    for (uint32 i = 0; i < 5; ++i)
    {
        data << uint32(0);                                  // currency id
        data << uint32(0);                                  // currency count
    }

    // Item costs (from extended cost, 5 slots)
    for (uint32 i = 0; i < 5; ++i)
    {
        data << uint32(0);                                  // item id
        data << uint32(0);                                  // item count
    }

    data << uint32(proto->BuyPrice);                        // money cost

    session.SendPacket(&data);
}

/*
 * Handles the packet sent by the client when requesting information about item text.
 *
 * This function is called when player clicks on item which has some flag set
 */
void ItemHandlers::HandleItemTextQuery(WorldSession& session, WorldPacket& recv_data)
{
    ObjectGuid itemGuid;
    recv_data >> itemGuid;

    DEBUG_LOG("CMSG_ITEM_TEXT_QUERY item guid: %u", itemGuid.GetCounter());

    WorldPacket data(SMSG_ITEM_TEXT_QUERY_RESPONSE, (4 + 10)); // guess size

    if (Item* item = session.GetPlayer()->GetInventoryMgr().GetItemByGuid(itemGuid))
    {
        data << uint8(0);                                   // has text
        data << ObjectGuid(itemGuid);                       // item guid
        data << item->GetText();
    }
    else
    {
        data << uint8(1);                                   // no text
    }
    session.SendPacket(&data);
}

void ItemHandlers::HandleReforgeItem(WorldSession& session, WorldPacket& recvData)
{
    uint32 slot, reforgeEntry;
    ObjectGuid guid;
    uint32 bag;
    Player* player = session.GetPlayer();

    recvData >> reforgeEntry >> slot >> bag;
    recvData.ReadGuidMask<2, 6, 3, 4, 1, 0, 7, 5>(guid);
    recvData.ReadGuidBytes<2, 3, 6, 4, 1, 0, 7, 5>(guid);

    if (!player->GetNPCIfCanInteractWith(guid, UNIT_NPC_FLAG_REFORGER))
    {
        sLog.outDebug("WORLD: HandleReforgeItemOpcode - Unit (GUID: %s) not found or player can't interact with it.", guid.GetString().c_str());
        session.SendReforgeResult(false);
        return;
    }

    Item* item = player->GetInventoryMgr().GetItemByPos(bag, slot);
    if (!item)
    {
        sLog.outDebug("WORLD: HandleReforgeItemOpcode - Player (Guid: %s) tried to reforge an invalid/non-existant item.", player->GetGuidStr().c_str());
        session.SendReforgeResult(false);
        return;
    }

    if (!reforgeEntry)
    {
        // Reset the item
        if (item->IsEquipped())
        {
            player->ApplyReforgeEnchantment(item, false);
        }

        item->ClearEnchantment(REFORGE_ENCHANTMENT_SLOT);
        session.SendReforgeResult(true);
        return;
    }

    ItemReforgeEntry const* stats = sItemReforgeStore.LookupEntry(reforgeEntry);
    if (!stats)
    {
        sLog.outDebug("WORLD: HandleReforgeItemOpcode - Player (Guid: %s) tried to reforge an item with invalid reforge entry (%u).", player->GetGuidStr().c_str(), reforgeEntry);
        session.SendReforgeResult(false);
        return;
    }

    if (!item->GetReforgableStat(ItemModType(stats->Source_stat)) || item->GetReforgableStat(ItemModType(stats->FinalStat))) // Cheating, you cant reforge to a stat that the item already has, nor reforge from a stat that the item does not have
    {
        session.SendReforgeResult(false);
        return;
    }

    if (player->GetMoney() < uint64(item->GetSpecialPrice()))   // cheating
    {
        session.SendReforgeResult(false);
        return;
    }

    player->ModifyMoney(-int64(item->GetSpecialPrice()));
    item->SetEnchantment(REFORGE_ENCHANTMENT_SLOT, reforgeEntry, 0, 0);
    session.SendReforgeResult(true);

    if (item->IsEquipped())
    {
        player->ApplyReforgeEnchantment(item, true);
    }
}
