#ifndef MANGOS_H_REPUTATIONRECORDS
#define MANGOS_H_REPUTATIONRECORDS

#include "Platform/Define.h"
#include "SharedDefines.h"

/// The highest and the lowest standing a faction can have.
const int32 REPUTATION_CAP    =  42999;
const int32 REPUTATION_BOTTOM = -42000;

/// A reputation spillover row (the world database's spillover template): the factions that also
/// receive a change to one faction, each with its rate and the highest rank it still gains at.
struct RepSpilloverTemplate
{
    uint32 faction[MAX_SPILLOVER_FACTIONS];
    float faction_rate[MAX_SPILLOVER_FACTIONS];
    uint32 faction_rank[MAX_SPILLOVER_FACTIONS];
};

// We assume the rate is in general the same for all three types below, but chose to keep three for scalability and customization
struct RepRewardRate
{
    float quest_rate;                                       // We allow rate = 0.0 in database. For this case,
    float creature_rate;                                    // it means that no reputation are given at all
    float spell_rate;                                       // for this faction/rate type.
};

struct ReputationOnKillEntry
{
    uint32 repfaction1;
    uint32 repfaction2;
    bool is_teamaward1;
    uint32 reputation_max_cap1;
    int32 repvalue1;
    bool is_teamaward2;
    uint32 reputation_max_cap2;
    int32 repvalue2;
    bool team_dependent;
};

#endif
