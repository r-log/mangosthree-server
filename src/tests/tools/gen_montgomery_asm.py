# --------------------------------------------------------------------------- helpers

def t(j):
    """The accumulator limb j of an unrolled frame (t[-1] is the scratch limb)."""
    return f"qword ptr [rsp + {8 + 8 * j}]"


def prologue(name, frame, kind):
    """Pushes, the frame, the argument shuffle. kind: 'mul' (5 args) or 'sqr' (4 args).
    Leaves rdi z, rsi x, r10 y (mul), r11 m, r8 n0inv."""
    o = []
    o.append("        .balign 16")
    o.append(f"        .globl {name}")
    o.append("#if !WINDOWS_ABI")
    o.append(f"        .type {name}, @function")
    o.append("#endif")
    o.append(f"{name}:")
    o.append("#if WINDOWS_ABI")
    for r in ("rbp", "rbx", "r12", "r13", "r14", "r15", "rdi", "rsi"):
        o.append(f"        push {r}")
        o.append(f"        .pushreg {r}")
    o.append(f"        sub rsp, {frame}")
    o.append(f"        .allocstack {frame}")
    o.append("        .endprolog")
    if kind == "mul":
        o.append("        mov rdi, rcx")
        o.append("        mov rsi, rdx")
        o.append("        mov r10, r8")
        o.append("        mov r11, r9")
        o.append(f"        mov r8, qword ptr [rsp + {frame + 104}]")
    else:
        o.append("        mov rdi, rcx")
        o.append("        mov rsi, rdx")
        o.append("        mov r11, r8")
        o.append("        mov r8, r9")
    o.append("#else")
    o.append("        .cfi_startproc")
    for r in ("rbp", "rbx", "r12", "r13", "r14", "r15"):
        o.append(f"        push {r}")
        o.append("        .cfi_adjust_cfa_offset 8")
        o.append(f"        .cfi_rel_offset {r}, 0")
    o.append(f"        sub rsp, {frame}")
    o.append(f"        .cfi_adjust_cfa_offset {frame}")
    if kind == "mul":
        o.append("        mov r10, rdx")
        o.append("        mov r11, rcx")
    else:
        o.append("        mov r11, rdx")
        o.append("        mov r8, rcx")
    o.append("#endif")
    return o


def epilogue(name, frame, tag):
    """Erase the frame, release it, restore, return."""
    o = []
    o.append("        // ---- erase the frame, release it ---------------------------------")
    o.append("        xor eax, eax")
    o.append(f"        mov rcx, {frame}")
    o.append(f".L{tag}_erase:")
    o.append("        sub rcx, 8")
    o.append("        mov qword ptr [rsp + rcx], rax")
    o.append(f"        jnz .L{tag}_erase")
    o.append("        xor edx, edx")
    o.append("        xor r8d, r8d")
    o.append("        xor r12d, r12d")
    o.append("        xor r14d, r14d")
    o.append(f"        add rsp, {frame}")
    o.append("#if WINDOWS_ABI")
    for r in ("rsi", "rdi", "r15", "r14", "r13", "r12", "rbx", "rbp"):
        o.append(f"        pop {r}")
    o.append("        ret")
    o.append("#else")
    o.append(f"        .cfi_adjust_cfa_offset -{frame}")
    for r in ("r15", "r14", "r13", "r12", "rbx", "rbp"):
        o.append(f"        pop {r}")
        o.append("        .cfi_adjust_cfa_offset -8")
    o.append("        ret")
    o.append("        .cfi_endproc")
    o.append(f"        .size {name}, .-{name}")
    o.append("#endif")
    return o


def product(src, acc_in, acc_out):
    """One product step: rdx * [src] added at acc_in, stored at acc_out, carry in r12."""
    return [
        f"        mulx rbx, rax, {src}",
        f"        adcx rax, {acc_in}",
        "        adox rax, r12",
        f"        mov {acc_out}, rax",
        "        mov r12, rbx",
    ]


def final_subtraction(k, top, base):
    """z = t - m kept if top != 0 or no borrow, else z = t. base(j) names t[j]; top names t[k]."""
    o = []
    o.append("        // ---- z = t - m, kept if t[k] != 0 or no borrow; else z = t ----------")
    o.append("        xor r15d, r15d")
    for j in range(k):
        o.append(f"        mov rax, {base(j)}")
        o.append(f"        sbb rax, qword ptr [r11 + {8 * j}]")
        o.append(f"        mov qword ptr [rdi + {8 * j}], rax")
    o.append("        sbb rbx, rbx")
    o.append(f"        mov rax, {top}")
    o.append("        neg rax")
    o.append("        sbb rax, rax")
    o.append("        not rbx")
    o.append("        or rax, rbx")
    o.append("        mov rbx, rax")
    o.append("        not rbx")
    for j in range(k):
        o.append(f"        mov rcx, qword ptr [rdi + {8 * j}]")
        o.append("        and rcx, rax")
        o.append(f"        mov rdx, {base(j)}")
        o.append("        and rdx, rbx")
        o.append("        or rcx, rdx")
        o.append(f"        mov qword ptr [rdi + {8 * j}], rcx")
    return o


# --------------------------------------------------------------------------- montmul, unrolled

def montmul_unrolled(k):
    name = f"mangos_montmul{k}_adx"
    tag = f"mm{k}"
    frame = 8 * (k + 3)          # scratch + t[0 .. k+1]
    o = []
    o.append("")
    o.append(f"// ---- {name}: k = {k}, every loop written out -----------------------------")
    o += prologue(name, frame, "mul")
    o.append("        // t[0 .. k+1] = 0")
    o.append("        xor eax, eax")
    for j in range(k + 2):
        o.append(f"        mov {t(j)}, rax")
    o.append("        xor r13d, r13d")
    o.append("        mov rcx, rsi")
    o.append(f"        lea r15, [rsi + {8 * k}]")
    o.append(f".L{tag}_pass:")
    o.append("        // ---- t += x[i] * y ------------------------------------------------")
    o.append("        mov rdx, qword ptr [rcx]")
    o.append("        xor r12d, r12d")
    for j in range(k):
        o += product(f"qword ptr [r10 + {8 * j}]", t(j), t(j))
    o.append("        // t[k] += carry + CF + OF; t[k+1] = what overflows")
    o.append(f"        mov rax, {t(k)}")
    o.append("        adcx rax, r12")
    o.append("        adox rax, r13")
    o.append(f"        mov {t(k)}, rax")
    o.append("        mov rax, r13")
    o.append("        adcx rax, r13")
    o.append("        adox rax, r13")
    o.append(f"        mov {t(k + 1)}, rax")
    o.append("        // ---- t = (t + u * m) / 2^64, u = t[0] * n0inv --------------------")
    o.append(f"        mov rdx, {t(0)}")
    o.append("        imul rdx, r8")
    o.append("        xor r12d, r12d")
    for j in range(k):
        o += product(f"qword ptr [r11 + {8 * j}]", t(j), t(j - 1))
    o.append("        // t[k-1] = t[k] + carry + CF + OF; t[k] = t[k+1] + what overflows")
    o.append(f"        mov rax, {t(k)}")
    o.append("        adcx rax, r12")
    o.append("        adox rax, r13")
    o.append(f"        mov {t(k - 1)}, rax")
    o.append(f"        mov rax, {t(k + 1)}")
    o.append("        adcx rax, r13")
    o.append("        adox rax, r13")
    o.append(f"        mov {t(k)}, rax")
    o.append("        lea rcx, [rcx + 8]")
    o.append("        cmp rcx, r15")
    o.append(f"        jb .L{tag}_pass")
    o += final_subtraction(k, t(k), t)
    o += epilogue(name, frame, tag)
    return o


# --------------------------------------------------------------------------- montsqr, unrolled

def montsqr_unrolled(k):
    name = f"mangos_montsqr{k}_adx"
    tag = f"ms{k}"
    frame = 8 * (2 * k + 2)      # scratch + t[0 .. 2k]
    o = []
    o.append("")
    o.append(f"// ---- {name}: k = {k}; the triangle, doubled, plus the diagonal; then in-place reduction")
    o += prologue(name, frame, "sqr")
    o.append("        // t[0 .. 2k] = 0")
    o.append("        xor eax, eax")
    for j in range(2 * k + 1):
        o.append(f"        mov {t(j)}, rax")
    o.append("        xor r13d, r13d")
    o.append("        // ---- the upper triangle: for i, t += x[i] * x[i+1 ..] at offset i -----")
    for i in range(k - 1):
        o.append(f"        mov rdx, qword ptr [rsi + {8 * i}]")
        o.append("        xor r12d, r12d")
        for j in range(i + 1, k):
            o += product(f"qword ptr [rsi + {8 * j}]", t(i + j), t(i + j))
        # position i + k was untouched so far: the last carry, plus both chain carries
        o.append("        adcx r12, r13")
        o.append("        adox r12, r13")
        o.append(f"        mov {t(i + k)}, r12")
    o.append("        // ---- t = 2t: one add-with-carry chain over the 2k limbs --------------")
    o.append("        xor eax, eax")
    for p in range(2 * k):
        o.append(f"        mov rax, {t(p)}")
        o.append("        adc rax, rax")
        o.append(f"        mov {t(p)}, rax")
    o.append("        // ---- t += x[i]^2 at offset 2i: one chain, each limb visited once ------")
    o.append("        xor r12d, r12d")
    for i in range(k):
        o.append(f"        mov rdx, qword ptr [rsi + {8 * i}]")
        o.append("        mulx rbx, rax, rdx")
        o.append(f"        adcx rax, {t(2 * i)}")
        o.append(f"        mov {t(2 * i)}, rax")
        o.append(f"        adcx rbx, {t(2 * i + 1)}")
        o.append(f"        mov {t(2 * i + 1)}, rbx")
    o.append("        // ---- reduce in place: row i adds q_i * m at offset i, q_i = t[i] * n0inv;")
    o.append("        // the carry out of a row is folded into the next row's top limb (r14)")
    o.append("        xor r14d, r14d")
    o.append("        lea rbp, [rsp + 8]")
    o.append(f"        mov rcx, {k}")
    o.append(f".L{tag}_row:")
    o.append("        mov rdx, qword ptr [rbp]")
    o.append("        imul rdx, r8")
    o.append("        xor r12d, r12d")
    for j in range(k):
        o += product(f"qword ptr [r11 + {8 * j}]", f"qword ptr [rbp + {8 * j}]", f"qword ptr [rbp + {8 * j}]")
    o.append(f"        mov rax, qword ptr [rbp + {8 * k}]")
    o.append("        adcx rax, r12")
    o.append("        adox rax, r14")
    o.append(f"        mov qword ptr [rbp + {8 * k}], rax")
    o.append("        mov r14, r13")
    o.append("        adcx r14, r13")
    o.append("        adox r14, r13")
    o.append("        lea rbp, [rbp + 8]")
    o.append("        sub rcx, 1")
    o.append(f"        jnz .L{tag}_row")
    o.append(f"        mov {t(2 * k)}, r14")
    o += final_subtraction(k, t(2 * k), lambda j: t(k + j))
    o += epilogue(name, frame, tag)
    return o


