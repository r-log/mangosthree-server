#!/usr/bin/env python3
"""Generate src/shared/Crypto/MontgomeryAsm.S, the assembly tier of the Montgomery kernel.

The listing has five procedures, all x86-64 with BMI2 + ADX, GAS Intel syntax, both
ABIs under WINDOWS_ABI (the MASM twin is produced from the output by gas2masm.py):

  mangos_montmul_adx(z, x, y, m, n0inv, k)   generic k (a positive multiple of 4), looped
  mangos_montmul16_adx / mangos_montmul32_adx(z, x, y, m, n0inv)   the same CIOS, unrolled
  mangos_montsqr16_adx / mangos_montsqr32_adx(z, x, m, n0inv)      a dedicated squaring

Why generated: the unrolled procedures are the generic one with every loop replaced
by straight-line code. Measured on the development machine, the product step -- mulx,
adcx of the accumulator limb, adox of the carry, store -- costs 1.1 TSC ticks in a
straight line and 2.0 inside the generic loop, whose flag-neutral control (jrcxz, lea,
jmp between every four products) is what the carry chains force on a loop. At the two
widths the server uses (the 1024-bit CRT halves, the 2048-bit modulus) the loops are
simply written out; the generic procedure stays for other multiples of four. The
squaring does k(k-1)/2 off-diagonal products (row scanning of the upper triangle),
doubles the sum with one add-with-carry chain, adds the k squares on the diagonal with
another, and reduces in place: k rows of q[i] * m at offset i, each row's carry folded
into the next row's top limb, the last one becoming the word above -- 1.5 k^2 products
instead of 2 k^2. Every procedure ends in the same masked subtraction.

Constant-time discipline as in the generic kernel: no branch, loop count or address
depends on data; the final subtraction is a mask; the frame is erased before return.

    python3 src/tests/tools/gen_montgomery_asm.py > src/shared/Crypto/MontgomeryAsm.S
    python3 src/tests/tools/gas2masm.py src/shared/Crypto/MontgomeryAsm.S > src/shared/Crypto/MontgomeryAsm.asm

A test regenerates both and compares them with the committed files.
"""
