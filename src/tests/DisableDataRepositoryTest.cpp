/// DisableDataRepository's row reads on the global WorldDatabase backed by fakes: every column of a
/// canned row lands in its member, typed as the loader read it.

#include "TestHarness.h"
#include "FakeDatabase.h"
#include "Database/DatabaseEnv.h"
#include "persistence/world/DisableDataRepository.h"

#include <vector>

namespace
{
    /// The fakes on the global world database.
    struct Db
    {
        FakeConnection query;
        FakeConnection async;
        SqlResultQueue results;
        AttachedFakes attached;

        Db() : query(WorldDatabase), async(WorldDatabase), attached(WorldDatabase, &query, &async, &results)
        {
        }
    };
}

// Each column of a `disables` row lands in its member, and the rows come back in order.
TEST(DisableDataRepository_Disables)
{
    Db db;
    db.query.Answer("SELECT", FakeRows{
        FakeRow{"1000", "1001", "102", "1003"},
        FakeRow{"2000", "2001", "202", "2003"},
    });
    std::vector<DisableRow> rows = DisableDataRepository::QueryDisables();
    REQUIRE(rows.size() == 2);
    CHECK_EQ(rows[0].sourceType, 1000u);
    CHECK_EQ(rows[0].entry, 1001u);
    CHECK_EQ(rows[0].flags, uint8(102));
    CHECK_EQ(rows[0].data, 1003u);
    CHECK_EQ(rows[1].sourceType, 2000u);
}
